test_that("all documented imports use explicit readers and retain IDs as text", {
  x <- minimum_case(); x$Case_ID <- "001"
  csv <- tempfile(fileext=".csv");write.csv(x,csv,row.names=FALSE)
  expect_identical(read_vragr_file(csv,"csv")$Case_ID,"001")
  writeLines(c('Case_ID,Category','001,NA'),csv)
  expect_identical(read_vragr_file(csv,"csv")$Category,"NA")
  eu <- tempfile(fileext=".csv");write.csv2(x,eu,row.names=FALSE)
  expect_identical(read_vragr_file(eu,"csv2")$Case_ID,"001")
  txt <- tempfile(fileext=".txt");write.table(x,txt,sep="\t",row.names=FALSE)
  expect_identical(read_vragr_file(txt,"txt")$Case_ID,"001")
  expect_identical(read_vragr_file(txt,"auto")$Case_ID,"001")
  sav <- tempfile(fileext=".sav");haven::write_sav(x,sav)
  expect_identical(as.character(read_vragr_file(sav,"sav")$Case_ID),"001")
  excel <- read_vragr_file(file.path(root,"tests/fixtures/cases.xlsx"),"xlsx",sheet=2)
  expect_identical(excel$Case_ID,"001")
})
test_that("malformed imports, duplicate/empty headers and empty files fail", {
  file <- tempfile(fileext=".csv")
  writeLines(c('a,a','1,2'),file);expect_error(read_vragr_file(file,"csv"),"unique")
  writeLines(c('a,','1,2'),file);expect_error(read_vragr_file(file,"csv"),"unique")
  writeLines(c('a,b','1,2,3'),file);expect_error(suppressWarnings(read_vragr_file(file,"csv")),"inconsistent")
  writeLines('a,b',file);expect_error(read_vragr_file(file,"csv"),"no data")
  expect_error(read_vragr_file('nonexistent.csv'),"no longer")
})
test_that("SAV imports accept the row limit and reject files exceeding it", {
  file <- tempfile(fileext = ".sav")
  haven::write_sav(data.frame(value = rep(1, 100000L)), file)
  expect_equal(nrow(read_vragr_file(file, "sav")), 100000L)
  haven::write_sav(data.frame(value = rep(1, 100001L)), file)
  expect_error(read_vragr_file(file, "sav"), "100,000 data rows")
})
test_that("category mappings are explicit and keyed by raw values, not their order", {
  x <- minimum_case();columns <- setNames(vragr_fields,vragr_fields)
  maps <- setNames(lapply(vragr_categories,function(f) setNames(vragr_choices(f),vragr_choices(f))),vragr_categories)
  expect_equal(vragr(prepare_vragr_data(x,columns,maps))$Score,-34)
  x$Item_1 <- "custom";expect_equal(vragr(prepare_vragr_data(x,columns,maps),strict=FALSE)$Status,"not_calculable")
  maps$Item_1 <- c(custom="Yes");expect_equal(vragr(prepare_vragr_data(x,columns,maps))$Score,-34)
  expect_equal(default_category("0","Item_1"),"")
  expect_equal(default_category("0","Item_1",c(Nein=0,Ja=1)),"No")
  expect_equal(mapping_input_id("Item_1","Sex","Male"),mapping_input_id("Item_1","Sex","Male"))
  expect_false(identical(mapping_input_id("Item_1","Sex","Male"),mapping_input_id("Item_4","Sex","Male")))
  maps$Item_1 <- c(custom="__missing__");expect_true(is.na(prepare_vragr_data(x,columns,maps)$Item_1))
  columns[2] <- columns[1];expect_error(prepare_vragr_data(x,columns,maps),"distinct")
})
test_that("named column mappings use input names rather than vector order", {
  x <- minimum_case()
  columns <- setNames(vragr_fields, vragr_fields)
  maps <- setNames(lapply(vragr_categories, function(field) {
    setNames(vragr_choices(field), vragr_choices(field))
  }), vragr_categories)
  expected <- prepare_vragr_data(x, columns, maps)
  expect_identical(prepare_vragr_data(x, rev(columns), maps), expected)
  expect_identical(prepare_vragr_data(x, unname(columns), maps), expected)
  names(columns)[1] <- "unknown"
  expect_error(prepare_vragr_data(x, columns, maps), "VRAG-R input names")
  names(columns)[1] <- names(columns)[2]
  expect_error(prepare_vragr_data(x, columns, maps), "VRAG-R input names")
})
test_that("exports preserve rows, invalid status, IDs, inputs, probabilities and UTC time", {
  x <- rbind(minimum_case(),minimum_case());x$Item_1[2] <- "invalid"
  time <- as.POSIXct("2026-10-31 13:45:17",tz="UTC")
  result <- make_vragr_export(x,vragr(x,strict=FALSE),ids=c("001","002"),timestamp=time,filename="data.csv")
  expect_equal(result$Status,c("calculated","not_calculable"));expect_true(is.na(result$Score[2]))
  expect_identical(result$Case_ID,c("001","002"));expect_equal(result$Prob_12_years[1],.15)
  expect_identical(result$Calculated_at_UTC,rep("2026-10-31T13:45:17Z",2))
  expect_match(vragr_export_filename("Results",time),"2026-10-31_13-45-17_UTC.csv",fixed=TRUE)
  expect_match(format_local_time(time),"14:45 CET",fixed=TRUE)
  expect_match(format_local_time(as.POSIXct("2026-07-01 12:00:00",tz="UTC")),"14:00 CEST",fixed=TRUE)
  expect_error(make_vragr_export(x,vragr(x,strict=FALSE),ids=c("1","1")),"unique")
  expect_equal(format_probability(.09,"de"),"9,0 %")
})
